#!/usr/bin/env python3
"""Generate independent Go modules' constants from the shared wire contract."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
limit = json.loads((root / "proto/contracts/meter-command-report.json").read_text())["max_failure_reason_bytes"]
if not isinstance(limit, int) or limit < 4:
    raise SystemExit("invalid failure reason byte limit")
for module, package in [("api-go", "domain"), ("edge-agent-go", "commands")]:
    target = root / f"services/{module}/internal/{package}/command_contract_generated.go"
    content = f'''// Code generated by scripts/generate_command_contract.py; DO NOT EDIT.

package {package}

// MaxFailureReasonBytes is the UTF-8 byte limit in the meter command report contract.
const MaxFailureReasonBytes = {limit}
'''
    if args.check:
        if not target.exists() or target.read_text() != content:
            raise SystemExit(f"{target.relative_to(root)} is stale; run scripts/generate_command_contract.py")
    else:
        target.write_text(content)
